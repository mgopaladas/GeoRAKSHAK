# ─── SCENARIO GENERATORS ─────────────────────────────────────

def _normal(station: dict, t: float, intensity: float = 1.0) -> dict:
    """Typical monsoon conditions — low/moderate readings."""
    return {
        "device_id": station["id"],
        "timestamp": datetime.utcnow().isoformat(),
        "latitude": station["lat"],
        "longitude": station["lon"],
        "rainfall_mm": random.uniform(0.5, 5) * intensity,
        "rainfall_1h": random.uniform(2, 12) * intensity,
        "rainfall_24h": random.uniform(8, 30) * intensity,
        "soil_moisture": random.uniform(28, 45) + 5 * math.sin(t / 10),
        "tilt_x": random.uniform(0.03, 0.15),
        "tilt_y": random.uniform(0.02, 0.12),
        "temperature": random.uniform(18, 26),
        "humidity": random.uniform(70, 88),
        "battery": max(70, station.get("battery", 90) - random.uniform(0, 0.3)),
        "signal_strength": random.randint(-80, -50),
    }


