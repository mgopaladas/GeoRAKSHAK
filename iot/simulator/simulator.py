SCENARIO_MAP = {
    "NORMAL": _normal,
    "HEAVY_RAIN": _heavy_rain,
    "GROUND_MOVEMENT": _ground_movement,
    "CRITICAL": _critical,
}


# ─── MAIN SIMULATOR ──────────────────────────────────────────

class SensorSimulator:
    """
    Publishes sensor data on MQTT topic: georakshak/sensors/{station_id}
    Optionally also POSTs to the HTTP API.
    """

    def __init__(self, mqtt_host: str = "localhost", mqtt_port: int = 1883, api_url: str = None):
        self.mqtt_host = mqtt_host
        self.mqtt_port = mqtt_port
        self.api_url = api_url
        self.client = None
        self.scenario = "NORMAL"
        self.intensity = 1.0
        self.running = False
        self.tick = 0

    def connect_mqtt(self):
        if mqtt is None:
            print("[WARN] paho-mqtt not installed, MQTT disabled")
            return
        self.client = mqtt.Client(client_id="georakshak-simulator")
        try:
            self.client.connect(self.mqtt_host, self.mqtt_port)
            self.client.loop_start()
            print(f"[MQTT] Connected to {self.mqtt_host}:{self.mqtt_port}")
        except Exception as e:
            print(f"[MQTT] Connection failed: {e}")
            self.client = None

    def publish(self, station: dict, data: dict):
        topic = f"georakshak/sensors/{station['id']}"
        payload = json.dumps(data)

        # MQTT publish
        if self.client:
            self.client.publish(topic, payload)

        # HTTP fallback/parallel
        if self.api_url and httpx:
            try:
                httpx.post(f"{self.api_url}/api/sensors/readings", json=data, timeout=5)
            except Exception as e:
                print(f"[HTTP] Failed for {station['id']}: {e}")

    def set_scenario(self, scenario: str, intensity: float = 1.0):
        self.scenario = scenario
        self.intensity = intensity
        print(f"[SIM] Scenario changed to {scenario} (intensity={intensity})")

    def run(self, interval: float = 5.0, stations: list = None):
        """Run the simulator loop."""
        self.connect_mqtt()
        self.running = True
        target_stations = stations or STATIONS

        print(f"[SIM] Starting simulator | Scenario: {self.scenario} | Stations: {len(target_stations)} | Interval: {interval}s")

        try:
            while self.running:
                generator = SCENARIO_MAP.get(self.scenario, _normal)
                for station in target_stations:
                    data = generator(station, self.tick, self.intensity)
                    self.publish(station, data)
                    print(f"  [{station['id']}] rain_1h={data['rainfall_1h']:.1f}mm soil={data['soil_moisture']:.1f}% tilt={data['tilt_x']:.2f}°")
                self.tick += 1
                time.sleep(interval)
        except KeyboardInterrupt:
            print("\n[SIM] Stopped")
        finally:
            self.running = False
            if self.client:
                self.client.loop_stop()
                self.client.disconnect()


