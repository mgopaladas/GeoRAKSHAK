if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(description="GeoRakshak Sensor Simulator")
    parser.add_argument("--scenario", default="NORMAL", choices=list(SCENARIO_MAP.keys()))
    parser.add_argument("--intensity", type=float, default=1.0)
    parser.add_argument("--interval", type=float, default=5.0)
    parser.add_argument("--mqtt-host", default=os.environ.get("MQTT_BROKER_HOST", "localhost"))
    parser.add_argument("--mqtt-port", type=int, default=int(os.environ.get("MQTT_BROKER_PORT", "1883")))
    parser.add_argument("--api-url", default=os.environ.get("API_URL", "http://localhost:8000"))
    args = parser.parse_args()

    sim = SensorSimulator(
        mqtt_host=args.mqtt_host,
        mqtt_port=args.mqtt_port,
        api_url=args.api_url,
    )
    sim.set_scenario(args.scenario, args.intensity)
    sim.run(interval=args.interval)
